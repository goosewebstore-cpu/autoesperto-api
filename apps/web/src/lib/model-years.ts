const FALLBACK_START = CURRENT - 19;

function norm(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

export function getModelYearRange(make: string, model: string): [number, number] {
  const key = `${norm(make)}|${norm(model)}`;
  const known = RANGES[key];
  if (known) return [known[0], Math.min(known[1], CURRENT)];
  return [FALLBACK_START, CURRENT];
}

export function getModelYears(make: string, model: string): number[] {
  const [start, end] = getModelYearRange(make, model);
  const years: number[] = [];
  for (let y = end; y >= start; y--) years.push(y);
  return years;
}

export function getRecentModelYears(make: string, model: string, count = 5): number[] {
  return getModelYears(make, model).slice(0, count);
}

export function isValidModelYear(make: string, model: string, year: number): boolean {
  if (!Number.isFinite(year)) return false;
  if (year < 1900 || year > CURRENT) return false;
  const [start, end] = getModelYearRange(make, model);
  return year >= start && year <= end;
}